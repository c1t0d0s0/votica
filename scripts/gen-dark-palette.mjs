// Generates src/dark-palette.css from Tailwind theme.css. Run: npm run gen:dark-palette
import { readFileSync, writeFileSync } from 'node:fs';
const theme = readFileSync('node_modules/tailwindcss/theme.css', 'utf8');
const vars = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (vars[m[1]] ||= {})[m[2]] = m[3].trim();
}
// Keep in sync with mirrorColorClasses() in src/lib/themes.ts
const NEUTRAL = new Set(['slate', 'gray', 'zinc', 'neutral', 'stone', 'mauve', 'mist', 'olive', 'taupe']);
const mirrorNeutral = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50 };
const mirrorChroma = { 50: 950, 100: 900, 200: 800, 300: 700, 700: 300, 800: 200, 900: 100, 950: 50 };
const dark = [], keep = [];
for (const [fam, shades] of Object.entries(vars)) {
  const map = NEUTRAL.has(fam) ? mirrorNeutral : mirrorChroma;
  for (const [shade, target] of Object.entries(map)) {
    if (!shades[shade] || !shades[target]) continue;
    // Chromatic light tints become deep, slightly transparent-feeling dark tints
    dark.push(`  --color-${fam}-${shade}: ${shades[target]};`);
    keep.push(`  --color-${fam}-${shade}: ${shades[shade]};`);
  }
}
const surface = vars.slate['900'];
const whiteVariants = [
  ['bg-white', 100], ['bg-white\\/95', 95], ['bg-white\\/90', 90], ['bg-white\\/80', 80], ['bg-white\\/50', 50],
  ['bg-white\\/20', 20], ['bg-white\\/15', 15], ['hover\\:bg-white', 100, ':hover'], ['focus\\:bg-white', 100, ':focus'],
];
const notKeep = ':not(.keep-palette, .keep-palette *)';
const scopes = ['.dark', '.palette-dark'];
const whiteRules = whiteVariants
  .map(([cls, pct, pseudo = '']) => {
    const value = pct === 100 ? 'var(--surface)' : `color-mix(in oklab, var(--surface) ${pct}%, transparent)`;
    return scopes.map(sc => `${sc} .${cls}${notKeep}${pseudo}`).join(',\n') + ` { background-color: ${value}; }`;
  })
  .join('\n');
const css = `/* AUTO-GENERATED by scripts/gen-dark-palette.mjs from tailwindcss/theme.css. Do not edit by hand.
 * Dark mode: the Tailwind palette is mirrored (light <-> dark shades) under html.dark (site-wide)
 * and under .palette-dark (pages using a dark poll design theme),
 * so existing utility classes adapt without adding dark: variants everywhere.
 * - Neutral families: full mirror (50<->950 ... 400<->600)
 * - Chromatic families: 50-300 <-> 700-950 (400-600 kept so colored buttons stay vivid)
 * - .keep-palette restores the original palette for parts that are intentionally dark
 *   (admin panel, dark buttons, colored hero cards).
 */
.dark,
.palette-dark {
  color-scheme: dark;
  --surface: ${surface};
${dark.join('\n')}
}

.dark .keep-palette,
.palette-dark .keep-palette {
  color-scheme: light;
${keep.join('\n')}
}

/* White surfaces become dark cards */
${whiteRules}
`;
// --- Safelist mirrored classes of dark poll themes ---
// getDisplayTheme() (src/lib/themes.ts) mirrors dark themes' palette classes at runtime; Tailwind only
// compiles class names that appear literally in source, so register the mirrored names here.
const NEUTRAL_LIST = [...NEUTRAL];
const TOKEN_RE = /^((?:[a-z0-9-]+:)*)((?:bg|text|border(?:-[trblxy])?|from|via|to|ring|ring-offset|shadow|divide|outline|fill|stroke|decoration|accent|caret)-)([a-z]+)-(\d{2,3})((?:\/\d+)?)$/;
const mirrorToken = token => {
  const m = token.match(TOKEN_RE);
  if (!m) return null;
  const [, variants, utility, family, shade, opacity] = m;
  const map = NEUTRAL_LIST.includes(family) ? mirrorNeutral : mirrorChroma;
  const target = map[shade];
  return target ? `${variants}${utility}${family}-${target}${opacity}` : null;
};
const themesSrc = readFileSync('src/lib/themes.ts', 'utf8');
const safelist = new Set();
for (const block of themesSrc.split(/\n  '[\w-]+': \{\n/).slice(1)) {
  if (!/isDark: true/.test(block)) continue;
  const classesPart = block.split('classes: {')[1] || '';
  for (const [, value] of classesPart.matchAll(/:\s*'([^']*)'/g)) {
    for (const token of value.split(/\s+/)) {
      const mirrored = mirrorToken(token);
      if (mirrored) safelist.add(mirrored);
    }
  }
}
const sortedSafelist = [...safelist].sort();
const safelistTs = `// AUTO-GENERATED by scripts/gen-dark-palette.mjs. Do not edit by hand.
// Mirrored palette classes of dark poll themes (see getDisplayTheme in themes.ts).
// Listed here as string literals so Tailwind compiles them (it only scans literal class names).
export const DARK_THEME_SAFELIST: readonly string[] = [
${sortedSafelist.map(c => `  '${c}',`).join('\n')}
];
`;

writeFileSync('src/dark-palette.css', css);
writeFileSync('src/lib/darkThemeSafelist.generated.ts', safelistTs);
console.log('safelisted', safelist.size);
console.log('families', Object.keys(vars).length, 'vars', dark.length);
